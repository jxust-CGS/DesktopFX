# -*- coding: utf-8 -*-
"""Regenerate 启动桌面特效.bat with portable lookup + CRLF/ASCII.

Why a generator: cmd.exe needs ASCII-only + CRLF (see the bat's own header).
Edit the BAT_TEXT below and re-run `python _make_launcher.py`, never edit the
.bat through Git Bash (MSYS mangles backslashes and line endings).
"""
import os

BAT_TEXT = r"""@echo off
setlocal

rem ============================================================
rem   DesktopFX - portable launcher
rem
rem   MUST stay ASCII-only AND use CRLF. Generated by
rem   _make_launcher.py - edit there, then re-run it.
rem
rem   Lookup order:
rem     python : env DESKTOP_FX_PY -> dev fallbacks -> "python" on PATH
rem     venv   : env DESKTOP_FX_VENV -> dev venv -> %LOCALAPPDATA%\DesktopFX\venv
rem
rem   First run on a new PC creates the venv (under %LOCALAPPDATA%) and
rem   installs numpy + Pillow via pip (Tsinghua mirror). Needs Python and
rem   network once; after that the app is fully offline.
rem ============================================================

set "ROOT=%~dp0"

rem ---------- pick base python ----------
set "PYEXE="
if defined DESKTOP_FX_PY set "PYEXE=%DESKTOP_FX_PY%"
if not defined PYEXE if exist "C:\Python314\python.exe" set "PYEXE=C:\Python314\python.exe"
if not defined PYEXE if exist "C:\Users\hspcadmin\.workbuddy\binaries\python\versions\3.13.12\python.exe" set "PYEXE=C:\Users\hspcadmin\.workbuddy\binaries\python\versions\3.13.12\python.exe"
if not defined PYEXE where python >nul 2>nul && set "PYEXE=python"

if not exist "%ROOT%desktop_fx.py" goto NOSCRIPT
if not defined PYEXE goto NOPYTHON

rem ---------- pick venv ----------
set "VENV=%LOCALAPPDATA%\DesktopFX\venv"
if defined DESKTOP_FX_VENV set "VENV=%DESKTOP_FX_VENV%"
if not defined DESKTOP_FX_VENV if exist "C:\Users\hspcadmin\.workbuddy\binaries\python\envs\desktop_fx" set "VENV=C:\Users\hspcadmin\.workbuddy\binaries\python\envs\desktop_fx"

set "VENV_PY=%VENV%\Scripts\python.exe"
set "VENV_PYW=%VENV%\Scripts\pythonw.exe"

if not exist "%VENV_PY%" goto SETUP
"%VENV_PY%" -c "import numpy, PIL" 1>nul 2>nul
if errorlevel 1 goto INSTALL
goto RUN

:SETUP
echo Setting up the runtime environment, please wait...
"%PYEXE%" -m venv --system-site-packages "%VENV%"
if errorlevel 1 goto VENVFAIL
if not exist "%VENV_PY%" goto VENVFAIL

:INSTALL
echo Installing dependencies (numpy + Pillow), please wait...
"%VENV_PY%" -m pip install -q -i https://pypi.tuna.tsinghua.edu.cn/simple numpy Pillow
if errorlevel 1 goto PIPFAIL
goto RUN

:RUN
if not exist "%VENV_PYW%" goto VENVFAIL
start "" /D "%ROOT%." "%VENV_PYW%" "%ROOT%desktop_fx.py"
endlocal
exit /b 0

:NOSCRIPT
echo ERROR: desktop_fx.py not found next to this launcher.
pause
endlocal
exit /b 1

:NOPYTHON
echo ERROR: Python 3.9+ not found.
echo Install from https://www.python.org and tick "Add python.exe to PATH",
echo or set DESKTOP_FX_PY to the full path of python.exe, then retry.
pause
endlocal
exit /b 1

:VENVFAIL
echo ERROR: could not create the virtual environment.
pause
endlocal
exit /b 1

:PIPFAIL
echo ERROR: could not install dependencies. Check network and retry.
pause
endlocal
exit /b 1
"""

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "启动桌面特效.bat")

lines = [ln for ln in BAT_TEXT.strip("\n").split("\n")]
# normalize: strip any stray CR, keep one trailing newline, write CRLF
body = "\r\n".join(ln.rstrip("\r") for ln in lines) + "\r\n"
assert body.isascii(), "bat must stay ASCII-only"

with open(OUT, "wb") as f:
    f.write(body.encode("ascii"))

print(f"wrote {OUT} ({len(body)} bytes, CRLF+ASCII)")
